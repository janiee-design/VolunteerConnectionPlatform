export function getONGsByArea(areaId: string): ONG[] {
  return ongs.filter((o) => o.area === areaId);
}

export function getONGById(id: string): ONG | undefined {
  return ongs.find((o) => o.id === id);
}

export function getAreaById(id: string): Area | undefined {
  return areas.find((a) => a.id === id);
}
